import { chromium } from 'playwright';
import fs from 'node:fs';
const out='E:/SAM/screenshots';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--no-sandbox']});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
page.on('pageerror',e=>errors.push('PAGE: '+e.message));
page.on('console',m=>{if(m.type()==='error')errors.push('CONSOLE: '+m.text())});
page.on('response',r=>{if(r.status()===404)errors.push('HTTP 404: '+r.url())});
const results={};
try {
  await page.goto('http://localhost:5173/',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Welcome back'}).waitFor();
  await page.screenshot({path:out+'/01-login-desktop.png',fullPage:true});
  results.loginDesktop='PASS';
  await page.getByRole('button',{name:'Create account'}).click();
  await page.getByLabel('Full name').fill('SAM QA');
  const testEmail='sam.qa.'+Date.now()+'@example.test';
  await page.getByLabel('Email address').fill(testEmail);
  await page.getByLabel('Password').fill('Sam-QA-Password-2026!');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByText('Good to see you, SAM').waitFor({timeout:15000});
  results.registerAndLogin='PASS';
  await page.screenshot({path:out+'/02-dashboard-desktop.png',fullPage:true});
  await page.locator('.sidebar .nav-item').filter({hasText:'My Files'}).click();
  await page.getByRole('heading',{name:'My Files'}).waitFor();
  await page.screenshot({path:out+'/03-files-desktop.png',fullPage:true});
  results.filesView='PASS';
  page.once('dialog',d=>d.accept('QA Folder'));
  await page.getByRole('button',{name:/New folder/}).click();
  await page.getByText('QA Folder').waitFor({timeout:10000});
  results.createFolder='PASS';
  const uploadInput=page.locator('input[type=file]').last();
  await uploadInput.setInputFiles({name:'sam-smoke.txt',mimeType:'text/plain',buffer:Buffer.from('SAM upload and download smoke test.')});
  await page.getByText('sam-smoke.txt').waitFor({timeout:10000});
  results.upload='PASS';
  await page.locator('.sidebar .nav-item').filter({hasText:'Clipboard'}).click();
  await page.getByRole('heading',{name:'Online Clipboard'}).waitFor();
  await page.locator('textarea').fill('SAM clipboard end-to-end check');
  await page.getByRole('button',{name:/Generate transfer code/}).click();
  const code=(await page.locator('.transfer-code strong').textContent()).trim();
  if(!/^\d{6}$/.test(code)) throw new Error('Clipboard code format invalid: '+code);
  await page.getByRole('button',{name:/Retrieve/}).click();
  await page.locator('.code-input').fill(code);
  await page.getByRole('button',{name:/Retrieve content/}).click();
  await page.getByText('SAM clipboard end-to-end check').waitFor();
  results.clipboardSendRetrieve='PASS';
  await page.locator('.sidebar .nav-item').filter({hasText:'Overview'}).click();
  await page.getByText('Good to see you, SAM').waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:out+'/04-dashboard-mobile.png',fullPage:true});
  const mobile=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,body:document.body.scrollWidth,overflow:document.documentElement.scrollWidth>innerWidth}));
  results.mobileLayout=mobile;
  await page.locator('.bottom-nav button').filter({hasText:'Files'}).click();
  await page.getByRole('heading',{name:'My Files'}).waitFor();
  await page.screenshot({path:out+'/05-files-mobile.png',fullPage:true});
  results.pageErrors=errors;
  console.log(JSON.stringify({results,errors},null,2));
} catch(e) {
  console.log(JSON.stringify({results,error:e.message,errors},null,2));
  process.exitCode=1;
} finally {
  await browser.close();
}
